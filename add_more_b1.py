json_path = 'storage/app/vocabularies/ielts_vocabularies.json'
with open(json_path, 'r', encoding='utf-8') as f:
    data = json.load(f)

existing_b1_words = {item[0].lower() for item in data.get('B1', [])}
new_words = []

for line in new_words_data.strip().split('\n'):
    parts = line.split('|')
    if len(parts) == 3:
        word, pos, meaning = parts
        if word.lower() not in existing_b1_words:
            new_words.append([word, meaning, pos])
            existing_b1_words.add(word.lower())

if 'B1' not in data:
    data['B1'] = []

data['B1'].extend(new_words)

# Sort them alphabetically
data['B1'] = sorted(data['B1'], key=lambda x: x[0].lower())

with open(json_path, 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=4)

print(f"Added {len(new_words)} new words. Total B1 words: {len(data['B1'])}")
