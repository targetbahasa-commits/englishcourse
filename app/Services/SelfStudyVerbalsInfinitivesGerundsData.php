            'banner_subtitle' => 'Kuasai pola dasar pelengkap kata kerja: kapan menggunakan to-infinitive, kapan menggunakan gerund (V-ing), infinitif penunjuk tujuan, kombinasi preposisi + gerund, dan pola verb + object + to-infinitive, melalui kalimat sehari-hari yang mudah dipahami.',
