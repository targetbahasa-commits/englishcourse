    <div class="rules-box">
        <strong class="title">Aturan Penting Modal & SEOM (Similar Expressions of Modals):</strong>
        <ol>
            <li><strong>Modal Murni Selalu Diikuti Bare Infinitive (V1) atau be:</strong> Tidak boleh ditambahkan akhiran <em>-s, -es, -ed, -ing</em> atau kata <em>to</em> (contoh benar: <em>She can speak</em>; contoh salah: <em>She can speaks / to speak</em>).</li>
            <li><strong>Larangan Double Modal:</strong> Dua modal murni tidak boleh berurutan (contoh salah: <em>will can</em>, <em>must can</em>). Gunakan <strong>SEOM / Phrasal Modal</strong> untuk modal kedua:
                <ul>
                    <li><em>I will <strong>be able to</strong> attend tomorrow.</em> (benar)</li>
                    <li><em>They might <strong>have to</strong> reschedule.</em> (benar)</li>
                    <li><em>Students should <strong>be allowed to</strong> ask questions.</em> (benar)</li>
                </ul>
            </li>
        </ol>
