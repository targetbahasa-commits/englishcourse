            document.getElementById('bikes3-ans-40')
        ];

        function syncInputs() {
            inputs.forEach(function(inp, i) {
                inp.value = queue[i] || '';
            });
        }

        document.querySelectorAll('.bikes3-cb').forEach(function(cb) {
            cb.addEventListener('change', function() {
                if (this.checked) {
                    if (queue.length >= 3) {
                        // Remove oldest from queue and uncheck it
                        var oldest = queue.shift();
                        document.querySelectorAll('.bikes3-cb').forEach(function(el) {
                            if (el.value === oldest) el.checked = false;
                        });
                    }
                    queue.push(this.value);
                } else {
                    queue = queue.filter(function(v) { return v !== cb.value; });
                }
                syncInputs();
            });
        });
    })();
